EVIDENCE = re.compile(r"원장|내역|수집|홈택스|등기|대장|카드|계약|통장|장부|명부|주주|대조|실사|증빙|자료|외부|채권 명세|문답")


def _label(desc, key):
    t = re.split(r"[,(]", desc or "")[0]
    t = re.sub(r"\[\{?|\}?\]|\bbool\b|\bint\b|\{[^}]*\}|'[^']*'\s*또는\s*'[^']*'|Max|Min", "", t)
    t = re.sub(r"\s{2,}", " ", t).strip(" :·-")
    return t or key.split(".", 1)[-1]


def _source(key, desc):
    if key.startswith("외부.") or EVIDENCE.search(desc or ""): return "조사자료"
    return "명세서"


def guide(missing_rows, rules, schema):
    """missing_rows: precheck.run()['자료 부족'], rules: {id: Rule}, schema: {키: 설명}
    → [{주제, 명세서, 질문, 규칙수, 명세서칸:[..], 조사자료:[..], 규칙:[..]}] (규칙 많은 순)"""
    groups = {}
    for m in missing_rows:
        r = rules.get(m["규칙"])
        if not r: continue
        topic = re.match(r"(서식\d+)", r.서식)
        tkey = topic.group(1) if topic else "서식 간 대사"
        g = groups.setdefault(tkey, {"주제": r.서식 if not topic else re.sub(r"^서식\d+\s*", "", r.서식), "코드": tkey,
                                     "명세서": TOPIC.get(tkey, ("신고서 부속서식", ""))[0], "질문": TOPIC.get(tkey, ("", "관련 서식이 제출됐는가"))[1],
                                     "명세서칸": set(), "조사자료": set(), "규칙": []})
        for k in r.needs:
            desc = schema.get(k, "")
            (g["조사자료"] if _source(k, desc) == "조사자료" else g["명세서칸"]).add(_label(desc, k))
        g["규칙"].append(f"{r.id} {r.제목}")
    out = []
    for g in groups.values():
        g["규칙수"] = len(g["규칙"]); g["명세서칸"] = sorted(g["명세서칸"])[:8]; g["조사자료"] = sorted(g["조사자료"])[:8]
        out.append(g)
    return sorted(out, key=lambda x: -x["규칙수"])
