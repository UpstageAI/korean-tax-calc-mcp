def inv_rate(kind, size, method=None):
    """통합투자 기본공제율 상한. method '기본'|'임시'|None(둘 중 큰 율)."""
    if kind not in INV_BASE or size not in INV_BASE[kind]: raise Missing(f"투자 구분값 {kind}/{size}")
    b, t = INV_BASE[kind][size], INV_TEMP_2025[kind][size]
    return b if method == "기본" else t if method == "임시" else max(b, t)


