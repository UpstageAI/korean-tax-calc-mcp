RD_CUR = {"중소": 0.25, "유예1~3": 0.20, "유예4~5": 0.15, "중견": 0.08, "일반": 0.02}
RD_INC = {"중소": 0.50, "중견": 0.40, "일반": 0.25}
RD_SPECIAL_BASE = {"신성장": {"중소": 0.30, "유예1~3": 0.25, "유예4~5": 0.20, "중견": 0.20, "일반": 0.20},
                   "국가전략": {"중소": 0.40, "유예1~3": 0.35, "유예4~5": 0.30, "중견": 0.30, "일반": 0.30}}
RD_SPECIAL_MULT, RD_SPECIAL_ADD_CAP = 3, 0.10
_RD_CUR, _RD_INC = RD_CUR, RD_INC


def rd_rate(method, group, kind, ratio=None, midsize=None):
    """R&D 공제율 상한(ratio 없으면 가산율·일반기업 당기분은 한도값). method '증가분'|'당기분'."""
    if kind != "일반":
        add = RD_SPECIAL_ADD_CAP if ratio is None else min(ratio * RD_SPECIAL_MULT, RD_SPECIAL_ADD_CAP)
        return RD_SPECIAL_BASE[kind][group] + add
    if method == "증가분":
        if group.startswith("유예"):
            if midsize is None: raise Missing("RD.중견기업")
            group = "중견" if midsize else "일반"
        return RD_INC[group]
    if group == "일반" and ratio is not None: return min(ratio / 2, 0.02)
    return RD_CUR[group]


