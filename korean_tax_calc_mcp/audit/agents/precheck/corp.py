def _ksic_limit(code, table, special):
    """KSIC 코드 → 기준 금액(원). 세분류 특례 → 중분류(C10·E36·N76) → 대분류 순. S94(협회·단체) 등 미수록은 None."""
    c = str(code).strip().upper()
    for k in (c, c[:6], c[:5]):
        if k in special: return special[k] * 억
    if c.startswith("S94"): return None
    for k in (c[:3], c[:1]):
        if k in table: return table[k] * 억
    return None


