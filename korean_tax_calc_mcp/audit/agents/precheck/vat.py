def _deemed_rate(d):
    """13 §5-1 공제율. 반환 (분자, 분모)."""
    업, 개인 = d["사업자.업종"], d["사업자.구분"] == "개인"
    if 업 == "과세유흥장소": return (2, 102)
    if 업 == "음식점":
        if not 개인: return (6, 106)
        return (9, 109) if d["의제매입.과세표준"] <= 200_000_000 else (8, 108)
    if 업 == "제조(과자점·도정·제분·떡방앗간)" and 개인: return (6, 106)
    if 업.startswith("제조") and (개인 or d.get("사업자.중소기업")): return (4, 104)
    return (2, 102)


def _deemed_limit(d):
    """13 §5-1 한도율(우대한도 2027.12.31.까지)."""
    if d["사업자.구분"] == "법인": return 0.50
    b = d["의제매입.과세표준"]
    if d["사업자.업종"] == "음식점": return 0.75 if b <= 100_000_000 else 0.70 if b <= 200_000_000 else 0.60
    return 0.65 if b <= 200_000_000 else 0.55


