NOT_TEMP = ("혼인파탄", "독립", "해당없음")  # 별거_사유 중 일시 별거가 아닌 것


def _get(f, k):
    v = f.get(k)
    if v is None or v == "": return None
    if k in BOOLS:
        if isinstance(v, bool): return v
        if v == "모름": return None
        raise ValueError(f"livelihood_shared.{k}는 true|false|모름 중 하나(입력: {v})")
    if k == "별거_증빙_유형":
        vs = [v] if isinstance(v, str) else list(v)
        bad = [x for x in vs if x not in PROOF_TYPES]
        if bad: raise ValueError(f"livelihood_shared.별거_증빙_유형은 {'|'.join(PROOF_TYPES)} 중에서(입력: {', '.join(map(str, bad))})")
        return tuple(vs)
    v = _ALIAS.get(v, v)
    if v not in FACTS[k]:
        raise ValueError(f"livelihood_shared.{k}은(는) {'|'.join(FACTS[k])} 중 하나(입력: {v})")
    return None if v == "모름" else v


def facts_of(entry):
    return {k: _get(entry, k) for k in (*BOOLS, *FACTS, "별거_증빙_유형")}


def rebuttal_note():
    refs = ", ".join(r.split("(")[0] for r in RULINGS["반증"][:2])
    return ("주민등록 동일세대·동거는 생계 공동의 추정일 뿐 요건이 아님 — 객관 자료(공과금·관리비 명의, 금융 송금, 전화·인터넷 가입 이력 등)로 "
            f"생활비 각자 부담과 실거주·독립 생계가 확인되면 반증될 수 있음({refs}). 진술서만으로는 반증되지 않음. 최종 판단은 사실판단 사항")


def judge_facts(f, spouse=False):
    """사실관계 → (결론, 사유 목록, 결정·해석 목록, 확인할 항목 목록).
    결론: 생계 공동 | 생계 공동 추정 | 생계 별도 | 입력 확인 필요"""
    reg, live, cost, inc, sup, sep, lease = (f["주민등록_동일세대"], f["동거_사실"], f["생활비_공동부담"], f["독립생계_소득"],
                                             f["경제적_지원"], f["별거_사유"], f["별도_임대차"])
    tax_dep, deposit, married, proof = f["연말정산_부양가족_등록"], f["수입_상대방계좌_입금"], f["혼인_독립가구"], f["별거_증빙_유형"]
    same_house = live in ("같은집_공유구조", "같은집_독립구조")
    objective = bool(proof) and any(p in RULES["반증"]["객관_증빙"] for p in proof)
    statement_only = bool(proof) and not objective  # 진술서만·없음
    apart = live == "따로거주" or reg is False

    # 1) 사실판단으로 넘길 사정·입력 모순
    if sep == "혼인파탄":
        return ("입력 확인 필요", ["별거 사유가 혼인관계 파탄 — 생계 공동 여부는 사실판단, 특별한 사정은 명의자(납세자)가 증명"],
                RULINGS["혼인파탄"], ["별거_사유", "생활비_공동부담", "경제적_지원"])
    if same_house and sep and sep != "해당없음":
        return ("입력 확인 필요", [f"동거_사실={live}인데 별거_사유={sep} — 둘 중 하나가 잘못 입력됨"], [], ["동거_사실", "별거_사유"])

    # 2) 결정적·중요(긍정) 사실 → 생계 공동 (1차 기준: 동거 불요, 생활비 공동 부담)
    if cost in RULES["공동부담"]["생활비_값"]:
        why = ["생활비(공과금·관리비·식비)를 공동 부담하거나 지출이 섞여 있음 — 정의 그대로 생계 공동"]
        if live == "따로거주": why.append("따로 거주해도 동거는 요건 아님")
        return ("생계 공동", why, RULINGS["공동부담"] + RULINGS["정의"][:1], [])
    if inc in RULES["무소득_송금"]["소득_값"] and sup in RULES["무소득_송금"]["지원_값"]:
        why = ["친족 본인에게 독립 소득이 없고 상대방이 정기적으로 송금 — 상대방 재원으로 생활"]
        if sep and sep not in NOT_TEMP: why.append(f"별거 사유({sep})가 있어도 송금이 이어지면 생계 공동 유지")
        if married: why.append("혼인·분가 이력이 있어도 소득이 없으면 별도 생계로 보지 않음")
        return ("생계 공동", why, RULINGS["무소득_송금"], [])
    if deposit is True:
        return ("생계 공동", ["친족 본인 수입이 상대방 계좌로 들어감 — 생활자금이 섞여 있음"], RULINGS["수입_입금"] + RULINGS["정의"][:1], [])

    # 3) 제3자 지원(금융자료) → 생계 별도
    if sup in RULES["제3자_지원"]["지원_값"]:
        if live == "같은집_공유구조" or tax_dep is True:
            return ("입력 확인 필요", ["제3자 지원으로 생활한다는데 " + ("같은 집 공유구조에 산다고 함" if live == "같은집_공유구조" else "부양가족 공제 이력이 있음")
                                     + " — 생활비 흐름 확인 필요"], RULINGS["제3자_지원"], ["경제적_지원", "생활비_공동부담", "동거_사실"])
        return ("생계 별도", ["생활비 원천이 상대방이 아닌 제3자(처가 등)임이 금융자료로 확인"], RULINGS["제3자_지원"], [])

    # 4) 생계 별도: 안정 소득 + (따로 거주·별도 세대 또는 같은 집 독립구조·임대차) + 생활비 각자 + 지원 없음
    R = RULES["별도"]
    in_house_sep = live == "같은집_독립구조" or lease is True
    cost_sep = cost in R["생활비_값"] or (apart and cost in R["생활비_분리시_값"])
    if inc in R["소득_값"] and sup in R["지원_값"] and cost_sep and (apart or in_house_sep):
        why = ["친족 본인 명의 안정 소득", f"생활비 {cost}", f"경제적 지원 {sup}",
               "따로 거주" if live == "따로거주" else ("주민등록 별도 세대" if reg is False and not in_house_sep else
                                                  ("같은 집이나 독립 생활 구조" if live == "같은집_독립구조" else "같은 집 내 별도 임대차·월세 지급"))]
        if tax_dep is True:
            return ("입력 확인 필요", why + ["그런데 부양가족 공제 이력이 있음 — 생계 별도 주장과 모순"], RULINGS["연말정산"], ["연말정산_부양가족_등록", "생활비_공동부담"])
        if reg is True and not objective:
            return ("생계 공동 추정", ["주민등록상 동일세대 — 별거·별도 생계를 보이는 객관 자료가 없어 추정이 유지됨"
                                       + (" (진술서만 제출)" if statement_only else " (별거_증빙_유형 미입력)")] + why,
                    RULINGS["추정"][:2] + RULINGS["진술서만"] + RULINGS["소득만으로_부족"][:1], ["별거_증빙_유형"])
        if spouse:
            return ("입력 확인 필요", why + ["배우자는 주민등록 별도세대여도 동일세대·생계를 같이하는 자로 본 해석이 있어 반증 자료 확인 필요"],
                    RULINGS["배우자"] + RULINGS["혼인파탄"], ["별거_사유", "생활비_공동부담"])
        if reg is True: why.append("주민등록은 동일세대이나 객관 자료로 실거주·독립 생계가 확인됨")
        return ("생계 별도", why, R["결정·해석"] + (RULINGS["반증"] if reg is True else []), [])

    # 5) 혼인해 독립 가구 + 주소지 다름 → 생계 별도 (소득 없으면 제외)
    M = RULES["혼인_독립"]
    if (married is True and reg is not True and apart and inc not in M["제외_소득_값"] and sup != "정기송금_있음"
            and cost != "일방지원" and tax_dep is not True and not spouse):
        return ("생계 별도", ["친족이 혼인해 독립 가구를 이루고 주소지가 다름" + f"(소득: {inc})",
                              "소득이 없다면 분가 이력만으로는 별도 생계로 보지 않음"], M["결정·해석"] + M["예외"], [])

    # 6) 추정: 주민등록 동일세대·같은 집 공유구조·부양가족 공제 이력
    pc = RULES["추정"]["생활비_값"]
    presume = []
    if live == "같은집_공유구조" and cost in pc and lease is not True:
        presume.append("같은 집(출입·거실·주방 공유)에 살고 생활비 분담·정산 증빙 없음")
    if reg is True and live in (None, "같은집_공유구조") and cost in pc:
        presume.append("주민등록상 동일세대")
    if reg is True and statement_only and live in (None, "따로거주", "같은집_공유구조") and cost in pc + ("각자분담_증빙있음",):
        if "주민등록상 동일세대" not in presume:
            presume.append("주민등록상 동일세대 — 따로 산다는 주장의 증빙이 진술서뿐이라 추정 유지")
    if tax_dep is True:
        presume.append("한쪽이 다른 쪽을 연말정산 부양가족으로 공제받아 옴")
    if spouse and not presume and live != "따로거주" and cost in pc:
        presume.append("배우자(주민등록 별도세대여도 동일세대로 본 해석)")
    if presume:
        if inc == "안정소득_있음": presume.append("친족 본인 소득이 있어도 소득만으로는 생계 공동이 부정되지 않음")
        refs = (RULINGS["추정"] + (RULINGS["연말정산"] if tax_dep else []) + (RULINGS["배우자"] if spouse else [])
                + (RULINGS["진술서만"] if statement_only else []) + (RULINGS["소득만으로_부족"] if inc == "안정소득_있음" else []))
        need = ["별거_증빙_유형"] + [k for k in ("생활비_공동부담", "독립생계_소득", "경제적_지원", "동거_사실", "별도_임대차")
                                     if f.get(k) is None or k == "생활비_공동부담"]
        return ("생계 공동 추정", presume, list(dict.fromkeys(refs)), need)

    # 7) 그 밖: 핵심 사실 부족·충돌
    why, need = [], []
    if reg is True and live == "따로거주":
        why.append("주민등록은 동일세대인데 실제로는 따로 거주한다는 사실 — 객관 자료로 실거주 확인")
        need += ["주민등록_동일세대", "동거_사실", "별거_증빙_유형"]
    if inc == "안정소득_있음" and cost in (None, "각자분담_증빙없음"):
        why.append("소득은 있으나 생활비 분담 증빙 없음 — 소득만으로는 생계 별도로 보지 않음")
        need += ["생활비_공동부담"]
    if cost == "일방지원":
        why.append("생활비_공동부담=일방지원 — 누가 누구를 지원하는지(경제적_지원)와 친족 본인 소득으로 판정")
        need += ["경제적_지원", "독립생계_소득"]
    for k in ("생활비_공동부담", "독립생계_소득", "경제적_지원", "동거_사실"):
        if f.get(k) is None and k not in need: need.append(k)
    if not why: why.append("결정적 사실(생활비 공동부담, 무소득+정기송금, 수입 입금)도 생계 별도 요건(안정 소득·따로 거주 또는 별도 세대·생활비 각자·지원 없음)도 채워지지 않음")
    return ("입력 확인 필요", why, RULINGS["정의"], need)


def evidence_for(keys):
    return [f"{k}: {EVIDENCE[k]}" for k in dict.fromkeys(keys) if k in EVIDENCE]
