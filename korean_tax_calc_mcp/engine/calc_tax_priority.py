class 입력확인(Exception):
    def __init__(self, 문제: list[str], **extra):
        super().__init__("; ".join(문제))
        self.문제 = 문제
        self.extra = extra


def _d(s, 필드: str) -> date:
    try:
        return date.fromisoformat(str(s))
    except (ValueError, TypeError):
        raise 입력확인([f"{필드}={s!r} — YYYY-MM-DD 형식으로 입력"])


class _C:
    def __init__(self, i: int, raw: dict):
        self.i = i
        self.raw = raw
        self.종류 = raw.get("종류")
        self.이름 = raw.get("이름") or f"{i + 1}. {self.종류}"
        self.청구액 = int(raw.get("금액", 0))
        self.인정액 = self.청구액
        self.받은 = 0
        self.내역: list[dict] = []
        self.세목 = raw.get("세목")
        self.당해세 = False          # 당해세 순위(제35조③·지방세기본법 제71조①3호 괄호)로 배분하는지
        self.국세 = self.종류 in ("당해세", "국세")
        self.법정기일: date | None = None
        self.설정일: date | None = None
        self.압류일: date | None = None
        self.순위 = raw.get("순위")

    @property
    def 남은(self) -> int:
        return self.인정액 - self.받은

    def give(self, amt: int, 단계: str, 근거: str):
        if amt > 0:
            self.받은 += amt
            self.내역.append({"단계": 단계, "금액": amt, "근거": 근거})


def _안분(pool: int, cs: list[_C]) -> dict[int, int]:
    """남은 금액 비율로 pool 안분(원 미만 버림, 남는 원은 소수점이 큰 순·입력 순)."""
    need = {c.i: c.남은 for c in cs if c.남은 > 0}
    total = sum(need.values())
    if total <= pool:
        return need
    out = {k: pool * v // total for k, v in need.items()}
    rest = pool - sum(out.values())
    order = sorted(need, key=lambda k: (-(pool * need[k] % total), k))
    for k in order[:rest]:
        out[k] += 1
    return out


class _배분기:
    def __init__(self, pool: int):
        self.pool = pool
        self.단계: list[dict] = []
        self.식기록: list[dict] = []    # 계산식 단계용: 단계 시작 잔액·참여 채권 남은 금액·한도·배분

    def _기록(self, 단계: str, 근거: str, cs: list[_C], cap: int | None) -> dict:
        rec = {"단계": 단계, "근거": 근거, "가용": self.pool, "한도": cap,
               "남은": {c.i: c.남은 for c in cs if c.남은 > 0}, "참여": cs}
        self.식기록.append(rec)
        return rec

    def 안분(self, cs: list[_C], 단계: str, 근거: str, cap: int | None = None) -> int:
        rec = self._기록(단계, 근거, cs, cap)
        avail = self.pool if cap is None else min(self.pool, cap)
        alloc = _안분(avail, cs)
        used = 0
        for c in cs:
            a = alloc.get(c.i, 0)
            c.give(a, 단계, 근거)
            used += a
        self.pool -= used
        rec["배분"] = used
        self.단계.append({"단계": 단계, "참여": [c.이름 for c in cs], "배분": used, "근거": 근거})
        return used

    def 조세(self, cs: list[_C], 단계: str, 근거: str, cap: int | None = None) -> int:
        """조세 상호간: 압류한 조세가 교부청구 조세보다 먼저(국세기본법 제36조, 지방세기본법 제73조), 압류일 순.
        압류 없는(교부청구·참가압류) 조세끼리는 동순위 안분."""
        rec = self._기록(단계, 근거, cs, cap)
        left = self.pool if cap is None else min(self.pool, cap)
        used_total = 0
        압류 = sorted({c.압류일 for c in cs if c.압류일})
        groups = [[c for c in cs if c.압류일 == d] for d in 압류] + [[c for c in cs if not c.압류일]]
        for g in groups:
            if not g or left <= 0:
                continue
            alloc = _안분(left, g)
            for c in g:
                a = alloc.get(c.i, 0)
                c.give(a, 단계, 근거 + (f" · 압류 {c.압류일.isoformat()}(제36조 압류선착)" if c.압류일 and len(cs) > 1 else ""))
                used_total += a
                left -= a
        self.pool -= used_total
        rec["배분"] = used_total
        self.단계.append({"단계": 단계, "참여": [c.이름 for c in cs], "배분": used_total, "근거": 근거,
                         "조세": [c.i for c in cs], "받은조세": [c.i for c in cs if any(x["단계"] == 단계 for x in c.내역)]})
        return used_total


def _직전보유자_한도(직전보유자: dict | None, 설정일: date) -> tuple[int, dict]:
    """시행령 제18조③: 직전 보유자 체납액 한도."""
    if not 직전보유자:
        raise 입력확인(["양도전_설정=True 담보가 있는 2023.4.1. 이후 매각: 직전보유자 정보 필요(국세기본법 제35조①3호의2 단서, 시행령 제18조③)"],
                    필요입력={"prior_owner": "{한도} 또는 {체납: [{금액, 법정기일}], 보유전_전세권등: bool, 최초설정일?}"})
    if "한도" in 직전보유자:
        v = int(직전보유자["한도"])
        if v < 0:
            raise 입력확인(["prior_owner.한도는 0 이상"])
        return v, {"방법": "입력 한도", "한도": v}
    if 직전보유자.get("보유전_전세권등"):
        return 0, {"방법": "시행령 제18조③2호 — 직전 보유자가 보유하기 전에 설정된 전세권등이 있음", "한도": 0}
    if "체납" not in 직전보유자:
        raise 입력확인(["prior_owner에 한도 또는 체납 목록 필요"])
    기준 = _d(직전보유자["최초설정일"], "prior_owner.최초설정일") if 직전보유자.get("최초설정일") else 설정일
    합 = 0
    포함 = []
    for k, t in enumerate(직전보유자["체납"]):
        if "법정기일" not in t:
            raise 입력확인([f"prior_owner.체납[{k}]에 법정기일 필요"])
        d = _d(t["법정기일"], f"prior_owner.체납[{k}].법정기일")
        if d < 기준:
            합 += int(t["금액"])
            포함.append({"금액": int(t["금액"]), "법정기일": d.isoformat()})
    return 합, {"방법": f"시행령 제18조③1호 — 직전 보유자 보유기간 중 가장 빠른 전세권등 설정일({기준.isoformat()})보다 법정기일이 빠른 체납액 합계",
               "포함": 포함, "한도": 합}


def _배분_계산식(매각대금: int, 집행비용: int, 배당액: int, cs: list[_C], b: _배분기, 잔여: int) -> tuple[list, list]:
    """배분 단계별 잔액을 식으로: 단계 배분 = MIN(앞 단계 잔액, 참여 채권 요구액[, 한도]), 잔액 = 앞 잔액 − 배분.
    순위(어느 단계에 누가 들어가는지)는 판단이라 단계 설명에 두고, 동순위 안분·⑦ 대신 변제로 정해진 채권별 금액은 값(근거 표시)으로 둔다."""
