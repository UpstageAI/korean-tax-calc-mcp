NEW_LAW_DATE = date(2024, 1, 1)       # 법률 제17768호 부칙 제1조제5호
ITEM_2_2_DATE = date(2025, 1, 1)      # 법률 제20629호 부칙 제1조
RATE_2019 = date(2019, 1, 1)          # 대통령령 제29436호 부칙 제1조
RATE_2022 = date(2022, 6, 7)          # 대통령령 제32665호 부칙 제1조
MONTHLY_RATE = "0.0066"               # 시행령 제34조제2항(월 1만분의 66), 법 제56조제1항제2호의2(1만분의 66)
SMALL_NOTICE = 450_000                # 제56조제2항
ROUNDING = "가산세는 원 미만을 버리고, 납부할 때 10원 미만 끝수는 버림 — " + LOCAL_ROUNDING_BASIS

_R3 = ("1만분의 3", "0.0003", "지방세기본법 시행령 제34조(2017.3.27.까지 제33조)")
_R25 = ("10만분의 25", "0.00025", "지방세기본법 시행령 제34조(대통령령 제29436호, 2019.1.1. 시행)")
_R22 = ("10만분의 22", "0.00022", "지방세기본법 시행령 제34조제1항(대통령령 제32665호, 2022.6.7. 시행)")


def cause_before_2019(due: date) -> bool:
    """대통령령 제29436호 부칙 제2조 — 시행(2019.1.1.) 전에 가산세 부과 사유가 발생했는지(법정납부기한이 2018.12.30. 이전)."""
    return due + timedelta(days=1) < RATE_2019


def daily_rate_segments(due: date, days: int) -> list[dict]:
    """법정납부기한 다음 날부터 days일을 시행본별 1일 이율로 나눈다 — [{시작, 끝, 일수, 이율, 이율_표기, 근거}]."""
    start = due + timedelta(days=1)
    end = start + timedelta(days=days)          # 끝 다음 날
    if cause_before_2019(due):
        old = (_R3[0], _R3[1], _R3[2] + " — 대통령령 제29436호 부칙 제2조(시행 전 사유 발생분은 종전 이율)")
        cuts = [(date(1900, 1, 1), old), (RATE_2022, _R22)]
    else:
        cuts = [(date(1900, 1, 1), _R3), (RATE_2019, _R25), (RATE_2022, _R22)]
    out = []
    for i, (c, (label, rate, basis)) in enumerate(cuts):
        nxt = cuts[i + 1][0] if i + 1 < len(cuts) else date(9999, 12, 31)
        a, b = max(start, c), min(end, nxt)
        if b > a:
            out.append({"시작": a.isoformat(), "끝": (b - timedelta(days=1)).isoformat(), "일수": (b - a).days,
                        "이율": rate, "이율_표기": "1일 " + label, "근거": basis})
    if len(out) > 1 and out[-1]["이율"] == _R22[1]:
        out[-1]["근거"] += ", 대통령령 제32665호 부칙 제2조(시행일 전 기간분은 종전 이율)"
    return out


def local_withholding_penalty(unpaid: int, due: date, until: date, notice_due: date | None = None, paid_on: date | None = None,
                              notice_amount: int | None = None, pre2024: bool = False) -> dict:
    """지방소득세 특별징수 납부지연가산세. until = 자진납부일(고지 전) 또는 납세고지일(종전 2017.3.28.~2023 문언은 부과결정일).
    pre2024 = 2024.1.1. 전 납세의무 성립분(법률 제17768호 부칙 제6조) — 종전: 3% + 일수분, 10% 한도, 고지 후분은 지방세징수법 가산금이라 계산 안 함.
    그 뒤 성립분: 1호 3% + 2호 일수분(합계 10% 한도) + 2호의2(지정 납부기한 2025.1.1. 이후) + 3호 월 1만분의 66 × 경과 개월(60개월 한도,
    납세고지서별·세목별 45만원 미만 제외), 전체 50% 한도."""
    u = _x(unpaid)
    days = max(0, (until - due).days)                       # 다음 날부터 끝날까지(끝날 포함)
    segs = daily_rate_segments(due, days)
    p1 = u * _x("0.03")
    p2 = sum((u * _x(s["이율"]) * s["일수"] for s in segs), _x(0))
    cap10 = u * _x("0.10")
    pre = min(p1 + p2, cap10)
    noticed = notice_due is not None
    out = {"규정": "종전" if pre2024 else "개정", "일수": days, "3%분": _floor(p1), "일수분": _floor(p2), "한도_10%": _floor(cap10),
           "한도_적용": p1 + p2 > cap10, "기간별_이율": segs, "고지후_규정": None, "2호의2분": 0, "3호분": 0, "고지후분": 0,
           "경과_개월": 0, "소액_제외": False, "납세고지서_세액": None, "2호의2_적용": None, "한도_50%": None, "50%한도_적용": False}
    if pre2024:
        out["고지후_규정"] = "지방세징수법 가산금·중가산금(계산 안 함)" if noticed else None
        out["가산세"] = _floor(pre)
        return out
    post = _x(0)
    if noticed and paid_on is not None and paid_on > notice_due:
        out["고지후_규정"] = "개정"
        out["2호의2_적용"] = notice_due >= ITEM_2_2_DATE
        p22 = u * _x(MONTHLY_RATE) if out["2호의2_적용"] else _x(0)
        고지세액 = notice_amount if notice_amount is not None else unpaid + _floor(pre)
        out["납세고지서_세액"] = 고지세액
        p3 = _x(0)
        if 고지세액 < SMALL_NOTICE:
            out["소액_제외"] = True
        else:
            months = _civil_months_elapsed(notice_due + timedelta(days=1), paid_on - timedelta(days=1), cap=60)
            out["경과_개월"] = months
            p3 = u * _x(MONTHLY_RATE) * months
        out["2호의2분"], out["3호분"] = _floor(p22), _floor(p3)
        post = p22 + p3
        out["고지후분"] = _floor(post)
    cap50 = u * _x("0.5")
    out["한도_50%"] = _floor(cap50)
    out["50%한도_적용"] = pre + post > cap50
    out["가산세"] = _floor(min(pre + post, cap50))
    return out
