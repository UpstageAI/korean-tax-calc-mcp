ERA_OLD, ERA_2020, ERA_NEW = "2016~2019", "2020", "2021~"


def era(year):
    """개시연도 → 구간. None이면 현행."""
    if year is None or year >= 2021:
        return ERA_NEW
    return ERA_2020 if year == 2020 else ERA_OLD


