"""적격합병 자산조정계정 세무조정(법인세법 제44조의3제1항, 시행령 제80조의4제1항) — 합병등기일 시점의 조정만.

합병법인이 승계 자산을 장부에 계상한 금액을 세무상 가액(피합병법인의 장부가액)으로 되돌리는 조정을 자산별로 낸다.
- 시가 − 피합병법인 세무상 장부가액 > 0 → 자산조정계정 손금산입(△유보), < 0 → 익금산입(유보)
- 계상액 − 시가 ≠ 0 → 시가를 넘거나 못 미치게 계상한 부분(임의 평가증·평가감, 법 제42조제1항)
조문은 "차액을 익금에 산입하고 같은 금액을 자산조정계정으로 손금에 산입"이라고 적지만, 합병법인이 자산을 시가로 계상하면
그 차액은 장부에 이미 반영돼 있으므로 세무조정으로는 자산조정계정 쪽 한 줄만 나온다.
"""

_BASIS = [["법인세법", "제44조의3", "①", "적격합병 — 피합병법인의 자산을 장부가액으로 양도받은 것으로 하고 시가와의 차액을 자산별로 계상"],
          ["법인세법 시행령", "제80조의4", "①", "시가 − 장부가액 > 0: 익금산입 + 자산조정계정 손금산입, < 0: 손금산입 + 자산조정계정 익금산입. 감가상각자산은 감가상각비와 상계·가산, 그 밖의 자산은 처분 사업연도에 전액"],
          ["법인세법", "제42조", "①", "자산의 장부가액을 증액·감액한 경우 세무상 장부가액은 평가 전 가액"]]


def qualified_merger_asset_adjustment(assets):
    if not isinstance(assets, list) or not assets:
        return {"error": "입력 확인 필요 — assets에 자산을 1개 이상 넣는다"}
    rows, adj, 주의 = [], [], []
    for i, a in enumerate(assets):
        if not isinstance(a, dict):
            return {"error": f"입력 확인 필요 — assets[{i}]는 객체여야 함"}
        name = str(a.get("자산") or a.get("name") or f"자산{i + 1}")
        try:
            basis = int(a["세무상장부가액"]); fair = int(a["시가"])
        except (KeyError, TypeError, ValueError):
            return {"error": f"입력 확인 필요 — '{name}': 세무상장부가액(피합병법인)과 시가는 필수(원, 정수)"}
        booked = a.get("계상액")
        booked = fair if booked is None else int(booked)
        if min(basis, fair, booked) < 0:
            return {"error": f"입력 확인 필요 — '{name}': 금액은 0 이상"}
        dep = bool(a.get("감가상각자산", False))
        diff, over = fair - basis, booked - fair
        후속 = ("감가상각비와 상계(익금산입분은 감가상각비에 가산), 처분하면 남은 금액을 그 사업연도에 전액 익금·손금(영 제80조의4①1호)" if dep
               else "해당 자산을 처분하는 사업연도에 전액 익금·손금(영 제80조의4①2호)")
        row = {"자산": name, "세무상장부가액": basis, "시가": fair, "계상액": booked, "자산조정계정": diff, "시가_초과_계상액": over,
               "세무상_취득가액": basis, "자산조정계정_후속처리": 후속 if diff else "자산조정계정 없음"}
        if diff > 0:
            adj.append({"구분": "손금산입", "과목": f"자산조정계정({name})", "금액": diff, "소득처분": "△유보",
                        "근거": "법인세법 시행령 제80조의4①", "산식": f"시가 {fair:,} − 세무상 장부가액 {basis:,} = {diff:,}"})
        elif diff < 0:
            adj.append({"구분": "익금산입", "과목": f"자산조정계정({name})", "금액": -diff, "소득처분": "유보",
                        "근거": "법인세법 시행령 제80조의4①", "산식": f"세무상 장부가액 {basis:,} − 시가 {fair:,} = {-diff:,}"})
        if over > 0:
            adj.append({"구분": "손금산입", "과목": f"{name}(시가 초과 계상)", "금액": over, "소득처분": "△유보",
                        "근거": "법인세법 제42조①", "산식": f"계상액 {booked:,} − 시가 {fair:,} = {over:,}"})
        elif over < 0:
            adj.append({"구분": "익금산입", "과목": f"{name}(시가 미달 계상)", "금액": -over, "소득처분": "유보",
                        "근거": "법인세법 제42조①", "산식": f"시가 {fair:,} − 계상액 {booked:,} = {-over:,}"})
        rows.append(row)
    손금 = sum(x["금액"] for x in adj if x["구분"] == "손금산입")
    익금 = sum(x["금액"] for x in adj if x["구분"] == "익금산입")
    주의.append("조문(영 제80조의4①)의 '차액을 익금에 산입'하는 부분은 합병법인이 자산을 시가로 계상하면서 장부에 이미 반영됐다고 보고 따로 익금산입 줄을 내지 않았음. "
              "자산을 피합병법인 장부가액으로 계상했다면 계상액에 그 금액을 넣어 '시가 미달 계상' 조정과 함께 본다")
    주의.append("범위 밖: 적격 요건 판정, 합병매수차손익(영업권·염가매수차익), 포합주식·합병대가, 피합병법인 유보의 승계(영 제85조), 그 뒤 사업연도의 감가상각 상계·처분 추인, 사후관리 사유 발생 시 일시 익금산입(법 제44조의3③)")
    return {"결과": {"세무조정": adj, "손금산입_합계": 손금, "익금산입_합계": 익금}, "계산": {"자산별": rows},
            "판단": [{"항목": r["자산"], "결론": (f"자산조정계정 {r['자산조정계정']:,}원" if r["자산조정계정"] else "자산조정계정 없음")
                      + (f", 시가와 다르게 계상 {r['시가_초과_계상액']:,}원" if r["시가_초과_계상액"] else ""),
                      "근거": "법인세법 제44조의3①, 시행령 제80조의4①"} for r in rows],
            "근거": _BASIS, "주의": 주의}
