"""근로소득 특별세액공제·출산보육수당 연도별 조문 대조 회귀 테스트.

기댓값은 조문으로 손계산. 총급여 5,000만원 → 의료비 문턱 150만원(3%).
"""
from korean_tax_calc_mcp.engine import calc_income as I

본인 = {"name": "본인", "relation": "본인", "age": 40}


def _stc(year, persons, expenses, salary=50_000_000):
    return I.special_tax_credit(year, "근로", salary, [본인] + persons, expenses)


# ── 의료비 3호 미숙아·선천성이상아 (제59조의4②3호, 2022~ 20%) ──────────────

def test_미숙아_2023_3호_20퍼센트():
    # 일반 0 → 미달액 150만 / 3호 300만 - 150만 = 150만 × 20% = 300,000
    r = _stc(2023, [{"name": "아기", "relation": "직계비속", "age": 0}],
             [{"kind": "미숙아·선천성이상아", "amount": 3_000_000, "person": "아기"}])
    assert r["결과"]["의료비_세액공제"] == 300_000
    assert r["계산"]["의료비"]["3호_공제대상"] == 1_500_000


def test_미숙아_2021_별도공제율_전_일반의료비():
    # 2021년은 3호 신설 전 — 일반 의료비 300만 - 150만 = 150만 × 15% = 225,000
    r = _stc(2021, [{"name": "아기", "relation": "직계비속", "age": 0}],
             [{"kind": "미숙아·선천성이상아", "amount": 3_000_000, "person": "아기"}])
    assert r["결과"]["의료비_세액공제"] == 225_000
    assert r["계산"]["의료비"]["일반"] == 3_000_000


# ── 의료비 2호 중증질환자 등 (2017.12.19 개정, 2018~) ─────────────────────

_중증배우자 = {"name": "배우자", "relation": "배우자", "age": 40, "severe_illness": True}


def test_중증질환자_2017_일반의료비_700만한도():
    # 2017년 제59조의4②2호에 중증질환자 없음 → 1호 일반: min(1,200만-150만, 700만) × 15% = 1,050,000
    r = _stc(2017, [_중증배우자], [{"kind": "의료비", "amount": 12_000_000, "person": "배우자"}])
    assert r["계산"]["의료비"]["특정"] == 0
    assert r["결과"]["의료비_세액공제"] == 1_050_000
    assert any("2018년부터" in j["결론"] for j in r["판단"])


def test_중증질환자_2016_일반의료비():
    r = _stc(2016, [_중증배우자], [{"kind": "의료비", "amount": 12_000_000, "person": "배우자"}])
    assert r["결과"]["의료비_세액공제"] == 1_050_000


def test_중증질환자_2018_특정의료비_한도없음():
    # 2018년 2호라목 → (1,200만 - 150만) × 15% = 1,575,000
    r = _stc(2018, [_중증배우자], [{"kind": "의료비", "amount": 12_000_000, "person": "배우자"}])
    assert r["계산"]["의료비"]["특정"] == 12_000_000
    assert r["결과"]["의료비_세액공제"] == 1_575_000


# ── 의료비 2호나목 과세기간 개시일 현재 6세 이하 (2024~) ─────────────────

def _의료비_자녀(year, child):
    return _stc(year, [dict({"name": "자녀", "relation": "직계비속"}, **child)],
                [{"kind": "의료비", "amount": 12_000_000, "person": "자녀"}])


def test_6세이하_종료일5세_특정():
    r = _의료비_자녀(2024, {"age": 5})
    assert r["결과"]["의료비_세액공제"] == 1_575_000


def test_6세이하_종료일7세_개시일나이_없으면_입력확인():
    r = _의료비_자녀(2024, {"age": 7})
    assert r["error"].startswith("입력 확인 필요")
    assert "age_at_year_start" in r["문제"][0]


def test_6세이하_개시일6세_특정():
    r = _의료비_자녀(2024, {"age": 7, "age_at_year_start": 6})
    assert r["결과"]["의료비_세액공제"] == 1_575_000


def test_6세이하_생일로_개시일나이_계산():
    # 2017-03-01 출생 → 2024-01-01 현재 만 6세 → 특정
    assert _의료비_자녀(2024, {"age": 7, "birth_date": "2017-03-01"})["결과"]["의료비_세액공제"] == 1_575_000
    # 2017-01-01 출생 → 2024-01-01 현재 만 7세 → 일반 min(1,050만, 700만) × 15%
    assert _의료비_자녀(2024, {"age": 7, "birth_date": "2017-01-01"})["결과"]["의료비_세액공제"] == 1_050_000


def test_6세이하_2023은_특정아님():
    # 2호나목은 2024년 신설 — 2023년 5세 자녀 의료비는 일반
    r = _의료비_자녀(2023, {"age": 5})
    assert r["결과"]["의료비_세액공제"] == 1_050_000


# ── 1명당 연 한도는 사람별 합산 후 적용 ─────────────────────────────────

def test_안경_1명당_50만_합산():
    # 영 제118조의5①4호 1명당 연 50만원: 40만+40만 → 50만. 일반 300만+50만 - 150만 = 200만 × 15% = 300,000
    r = _stc(2020, [{"name": "배우자", "relation": "배우자", "age": 40}],
             [{"kind": "안경", "amount": 400_000, "person": "배우자"},
              {"kind": "안경", "amount": 400_000, "person": "배우자"},
              {"kind": "의료비", "amount": 3_000_000, "person": "배우자"}])
    assert r["계산"]["의료비"]["일반"] == 3_500_000
    assert r["결과"]["의료비_세액공제"] == 300_000
    assert any(j["항목"] == "안경" and "1명당" in j["결론"] for j in r["판단"])


def test_안경_사람마다_따로_한도():
    r = _stc(2020, [{"name": "배우자", "relation": "배우자", "age": 40},
                    {"name": "자녀", "relation": "직계비속", "age": 15}],
             [{"kind": "안경", "amount": 400_000, "person": "배우자"},
              {"kind": "안경", "amount": 400_000, "person": "자녀"}])
    assert r["계산"]["의료비"]["일반"] == 800_000


def test_안경_본인은_특정의료비():
    # 제59조의4②2호가목 해당 거주자 — 안경도 의료비(영 제118조의5①4호)
    r = _stc(2020, [], [{"kind": "안경", "amount": 600_000, "person": "본인"}])
    assert r["계산"]["의료비"]["특정"] == 500_000


