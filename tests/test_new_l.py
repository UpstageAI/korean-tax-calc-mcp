def test_input_check():
    r = c(T, {"loans": [{"interest": 1}], "year": 2025})
    assert r["error"].startswith("입력 확인 필요")
    r = c(T, {"loans": [{"interest": 1, "jeoksu": 1}], "advances": [{"대상": "직원", "사유": "급료가불", "금액": 1, "지급일": "2025-01-01"}], "year": 2025})
    assert "월정급여" in r["문제"][0]
    r = c(T, {"loans": [{"interest": 1, "jeoksu": 1}], "advances": [{"대상": "직원", "금액": 1, "지급일": "2025-01-01"}]})
    assert r["error"].startswith("입력 확인 필요")
