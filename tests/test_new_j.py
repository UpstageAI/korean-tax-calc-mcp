def test_전체_순서_손계산():
    # 배당할 금액 = 3억 − 300만 = 2억9,700만
    # 1) 소액임차 5,500 + 최우선임금 2,000 = 7,500 → 2억2,200만
    # 2) 당해세 재산세 200 → 2억2,000만
    # 3) 부가세(법정기일 2020-01-25 < 저당 2020-05-01) 1,000 → 2억1,000만
    # 4) 저당권 1억 → 1억1,000만  5) 일반임금 3,000 → 8,000만
    # 6) 소득세(법정기일 2021, 저당 뒤) 2,000 → 6,000만  7) 일반채권 1억 중 6,000만
    _reset_call_memo()
    r = tpd(sale_amount=30000 * M, execution_cost=300 * M, sale_date="2022-08-01", property_type="주택", claims=[
        {"이름": "임차인", "종류": "소액임차보증금", "금액": 5500 * M},
        {"이름": "근로자", "종류": "최우선임금채권", "금액": 2000 * M},
        {"이름": "재산세", "종류": "지방세", "당해세": True, "세목": "재산세", "금액": 200 * M, "법정기일": "2021-07-16"},
        {"이름": "부가세", "종류": "국세", "금액": 1000 * M, "확정방식": "신고", "기준일": "2020-01-25"},
        {"이름": "은행", "종류": "저당권", "금액": 10000 * M, "설정일": "2020-05-01"},
        {"이름": "임금", "종류": "일반임금채권", "금액": 3000 * M},
        {"이름": "소득세", "종류": "국세", "금액": 2000 * M, "법정기일": "2021-05-31"},
        {"이름": "대여금", "종류": "일반채권", "금액": 10000 * M}])
    assert r["결과"]["배당할_금액"] == 29700 * M
    for 이름, v in [("임차인", 5500), ("근로자", 2000), ("재산세", 200), ("부가세", 1000), ("은행", 10000),
                   ("임금", 3000), ("소득세", 2000), ("대여금", 6000)]:
        assert _amt(r, 이름) == v * M, 이름
    assert r["결과"]["잔여"] == 0


def test_최우선_부족하면_안분():
    # 배당할 금액 6,000: 소액 2,000(한도 3,000 안) + 최우선임금 4,000 = 6,000 → 전액
    # 배당할 금액 3,000: 1/2 한도 1,500 → 소액 인정 1,500, 최우선 합 5,500 중 3,000 안분
    _reset_call_memo()
    r = tpd(sale_amount=3000 * M, sale_date="2025-03-01", property_type="주택", claims=[
        {"이름": "임차인", "종류": "소액임차보증금", "금액": 2000 * M},
        {"이름": "근로자", "종류": "최우선임금채권", "금액": 4000 * M}])
    # 1,500 : 4,000 비율로 3,000 → 임차인 818만1,818원, 근로자 2,181만8,181원(+1원 끝수)
    assert _amt(r, "임차인") + _amt(r, "근로자") == 3000 * M
    assert _amt(r, "임차인") == 30_000_000 * 1500 // 5500


