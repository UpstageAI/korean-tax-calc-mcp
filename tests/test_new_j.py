"""국세 우선권에 따른 매각대금 배분(tax_priority_distribution) 회귀 테스트.

기댓값은 조문으로 손계산(국세기본법 제35조·제36조, 시행령 제18조③, 지방세기본법 제71조,
근로기준법 제38조, 주택임대차보호법 시행령 제10조). 단위 만원 → M.
"""
from korean_tax_calc_mcp.server import tax_priority_distribution as tpd, find_tool, _reset_call_memo

M = 10_000


def _amt(r, 이름):
    return next(x["배분액"] for x in r["결과"]["배분"] if x["이름"] == 이름)


def _양도재산(sale_date, 소득세_법정기일="2019-05-31", prior=None):
    _reset_call_memo()
    return tpd(sale_amount=8000 * M, sale_date=sale_date, claims=[
        {"이름": "종부세", "종류": "당해세", "세목": "종합부동산세", "금액": 1150 * M, "법정기일": "2023-12-15"},
        {"이름": "소득세", "종류": "국세", "금액": 4000 * M, "법정기일": 소득세_법정기일},
        {"이름": "은행", "종류": "근저당권", "금액": 10000 * M, "설정일": "2020-03-02", "양도전_설정": True}],
        prior_owner=prior or {"체납": [{"금액": 3500 * M, "법정기일": "2019-11-30"}], "보유전_전세권등": False})


# ── ①3호의2: 양도된 재산(2023.4.1. 이후 매각결정분) ──────────────────────────

def test_양도재산_직전보유자_한도_은행_3350만():
    # 8,000 − 종부세(③ 후단, 3호의2 재산도 종부세는 우선) 1,150 − 소득세(법정기일 < 설정일, 영18③1호 한도 3,500) 3,500
    # = 은행 3,350. 소득세 나머지 500은 은행 뒤 → 0.
    r = _양도재산("2024-06-10")
    assert _amt(r, "종부세") == 1150 * M
    assert _amt(r, "소득세") == 3500 * M
    assert _amt(r, "은행") == 3350 * M
    assert r["결과"]["잔여"] == 0


def test_양도재산_한도_직접입력():
    r = _양도재산("2024-06-10", prior={"한도": 3500 * M})
    assert _amt(r, "은행") == 3350 * M


def test_양도재산_직전보유자_보유전_전세권등_있으면_한도0():
    # 시행령 제18조③2호 → 한도 0: 은행 = 8,000 − 1,150 = 6,850
    r = _양도재산("2024-06-10", prior={"보유전_전세권등": True})
    assert _amt(r, "소득세") == 0
    assert _amt(r, "은행") == 6850 * M


def test_양도재산_2024년_법정기일이_설정일_뒤인_국세는_한도_밖():
    # 2024.1.1. 이후(법률 제19926호): 한도 안 국세는 법정기일이 설정일보다 빠른 것만 → 소득세(2021) 제외
    r = _양도재산("2024-06-10", 소득세_법정기일="2021-05-31")
    assert _amt(r, "소득세") == 0
    assert _amt(r, "은행") == 6850 * M


def test_양도재산_2023년_매각은_법정기일_한정_전():
    # 2023.4.1.~12.31. 매각결정: 단서 국세에 법정기일 한정 없음 → 소득세(2021)도 한도 3,500 안에서 우선
    r = _양도재산("2023-06-10", 소득세_법정기일="2021-05-31")
