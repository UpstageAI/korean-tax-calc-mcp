"""배당세액공제(소득세법 제56조)·비교산출세액(제62조) 회귀 테스트.

기댓값은 조문으로 손계산. 기본세율은 제55조 연도표(2016: 1,200만 6%·4,600만 15%·8,800만 24%·1.5억 35%,
2023~: 1,400만 6%·5,000만 15%·8,800만 24%·1.5억 35%). Gross-up 11%(2016~2023)·10%(2024~).
"""
import asyncio
import json

from korean_tax_calc_mcp.server import mcp


def _call(**args):
    return json.loads(asyncio.run(mcp.call_tool("dividend_tax_credit", args)).content[0].text)


# ── 1. 종합과세, 공제액 = Gross-up (한도 안) ─────────────────────────────────
def test_2024_공제액은_GrossUp():
    # 이자 1,000만 + 상장배당 4,000만 = 5,000만 > 2천만
    # 2천만 = 이자 1,000만 + 배당 1,000만 → Gross-up 대상 3,000만 × 10% = 300만 (제56조④, 시행령 제116조의2)
    # 이자소득등(GU 포함) 5,300만, 다른 과세표준 5,000만
    # 1호: 기본세율(5,300만 − 2천만 + 5,000만 = 8,300만) = 8,300만×24% − 576만 = 1,416만 + 280만 = 1,696만
    # 2호: 5,000만 × 14% = 700만 + 기본세율(5,000만) = 750만 − 126만 = 624만 → 1,324만
    # 한도 1,696만 − 1,324만 = 372만, 공제 = min(300만, 372만) = 300만
    r = _call(year=2024, items=[{"kind": "예금이자", "amount": 10_000_000},
                                {"kind": "상장법인현금배당", "amount": 40_000_000}], other_base=50_000_000)
    x = r["결과"]
    assert x["Gross-up"] == 3_000_000
    assert x["일반산출세액"] == 16_960_000
    assert x["비교산출세액"] == 13_240_000
    assert x["종합소득산출세액"] == 16_960_000
    assert x["배당세액공제한도"] == 3_720_000
    assert x["배당세액공제액"] == 3_000_000
    assert x["공제후세액"] == 13_960_000


def test_2024_숫자입력과_과세표준전체_입력도_같은값():
    r = _call(year=2024, grossup=3_000_000, financial_14=50_000_000, taxable_base=103_000_000)
    assert r["결과"]["배당세액공제액"] == 3_000_000
    assert r["결과"]["공제후세액"] == 13_960_000
    assert r["계산"]["다른 종합소득 과세표준"] == 50_000_000


# ── 2. 한도에 걸림 (제15조2호 후단: 공제 후 세액 ≥ 제62조2호 금액) ────────────
def test_2023_한도가_GrossUp보다_작음():
    # 상장배당 1억, 다른 소득 없음. Gross-up = (1억 − 2천만) × 11% = 880만
    # 1호: 기본세율(1억880만 − 2천만 = 8,880만) = 8,880만×35% − 1,544만 = 1,564만 + 280만 = 1,844만
    # 2호: 1억 × 14% = 1,400만
    # 한도 444만 < Gross-up 880만 → 공제 444만, 공제 후 세액 = 2호 금액 1,400만
    r = _call(year=2023, items=[{"kind": "상장법인현금배당", "amount": 100_000_000}], other_base=0)
    x = r["결과"]
    assert x["Gross-up"] == 8_800_000
    assert x["일반산출세액"] == 18_440_000
    assert x["비교산출세액"] == 14_000_000
    assert x["배당세액공제액"] == 4_440_000
    assert x["공제후세액"] == 14_000_000


# ── 3. 원천징수되지 않은 비영업대금 이익: 2016 14% → 2017~ 25% ──────────────
# 제62조2호 가목 단서 — 2016: 원천징수 안 된 소득은 제129조①1호라목(14%)
# 2017~: 비영업대금(제16조①11호)은 1호나목(25%). 법률 제14389호 부칙 제1조·제2조①(2017.1.1. 이후 발생 소득분)
_비영업 = [{"kind": "비영업대금이익", "amount": 10_000_000, "withheld": False},
         {"kind": "상장법인현금배당", "amount": 15_000_000}]


def test_2016_미원천_비영업대금_14퍼센트():
    # 합계 2,500만. 2천만 = 이자 1,000만 + 배당 1,000만 → Gross-up (1,500만 − 1,000만) × 11% = 55만
    # 1호: 기본세율(2,555만 − 2천만 + 3,000만 = 3,555만) = 533.25만 − 108만 = 425.25만 + 280만 = 7,052,500
    # 2호: (1,000만 + 1,500만) × 14% = 350만 + 기본세율(3,000만) 342만 = 692만
    # 한도 132,500 < Gross-up 550,000 → 공제 132,500
    x = _call(year=2016, items=_비영업, other_base=30_000_000)["결과"]
    assert x["일반산출세액"] == 7_052_500
    assert x["비교산출세액"] == 6_920_000
    assert x["배당세액공제액"] == 132_500


def test_2017_미원천_비영업대금_25퍼센트_비교과세():
    # 2호: 1,000만 × 25% + 1,500만 × 14% = 460만 + 342만 = 802만 > 1호 7,052,500 → 산출세액 = 2호, 공제 0
    x = _call(year=2017, items=_비영업, other_base=30_000_000)["결과"]
    assert x["일반산출세액"] == 7_052_500
    assert x["비교산출세액"] == 8_020_000
    assert x["종합소득산출세액"] == 8_020_000
    assert x["적용"].startswith("2호")
    assert x["배당세액공제액"] == 0


# ── 4. 2천만원 이하 + 출자공동사업자배당 (제62조 본문 후단·2호 나목 단서) ─────────
def test_2024_분리과세_출자공동_비교세액():
    # 예금이자 500만(원천징수) → 분리과세, 과세표준에 없음. 출자공동배당 1,000만이 다른 과세표준 전부.
    # 2호 나목: 기본세율(1,000만) 60만 < 비교세액 1,000만 × 14% + 기본세율(0) = 140만 → 140만
    x = _call(year=2024, items=[{"kind": "출자공동사업자배당", "amount": 10_000_000},
                                {"kind": "예금이자", "amount": 5_000_000}], other_base=10_000_000)["결과"]
    assert x["일반산출세액"] is None
    assert x["비교산출세액"] == 1_400_000
    assert x["배당세액공제액"] == 0


# ── 5. 지원하지 않는 경우·입력 오류는 계산하지 않음 ─────────────────────────
