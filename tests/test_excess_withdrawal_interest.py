"""초과인출금 지급이자 필요경비불산입 — 손계산 사례(지어낸 금액).

대조한 시행본: 소득세법 시행령 제61조·제78조의2, 시행규칙 제27조 2016.12.31.·2021.12.31.·2026.11.27. 기준(산식·순서 문언 같음).

사례 A (이자율 둘 + 채권자불분명 이자)
  3월 말: 부채 380,000,000 − 충당금 30,000,000 − 자산 300,000,000 = 초과인출금 50,000,000 × 31일 = 적수 1,550,000,000
  4월 말: 부채 330,000,000 − 충당금 30,000,000 − 자산 320,000,000 < 0 → 0
  연 15%: 이자 600,000(그중 채권자불분명 150,000), 적수 1,460,000,000 → 대상 이자 450,000, 대상 적수 1,095,000,000
  연 8%: 이자 1,600,000, 적수 7,300,000,000
  높은 이자율부터: 1,095,000,000은 15% 차입금에 → 450,000 전액. 남은 455,000,000은 8% 차입금에 → 1,600,000 × 455 ÷ 7,300 = 99,726.03
  합계 549,726.03 → 549,726원
"""
from test_form_templates import c

T = "excess_withdrawal_interest"
MONTHS = [{"기간": "3월", "자산": 300_000_000, "부채": 380_000_000, "충당금준비금": 30_000_000, "일수": 31},
          {"기간": "4월", "자산": 320_000_000, "부채": 330_000_000, "충당금준비금": 30_000_000, "일수": 30}]
LOANS = [{"이자율": 8, "지급이자": 1_600_000, "적수": 7_300_000_000},
         {"이자율": 15, "지급이자": 600_000, "적수": 1_460_000_000, "채권자불분명_이자": 150_000}]


def test_two_rates_higher_rate_first_after_unidentified_creditor_interest():
    r = c(T, {"borrowings": LOANS, "months": MONTHS})
    assert r["결과"]["필요경비불산입액"] == 549_726 and r["결과"]["선순위_채권자불분명_이자"] == 150_000
    assert r["계산"]["초과인출금_적수"] == 1_550_000_000
    assert [m["초과인출금"] for m in r["계산"]["기간별"]] == [50_000_000, 0]
    first, second = r["계산"]["이자율별"]
    assert first["이자율"] == 15 and first["필요경비불산입"] == 450_000 and first["배분된_초과인출금_적수"] == 1_095_000_000
    assert second["이자율"] == 8 and second["필요경비불산입"] == 99_726.03 and second["배분된_초과인출금_적수"] == 455_000_000
    # 총이자에 적수 비율을 한 번에 곱한 값(2,050,000 × 1,550 ÷ 8,395 = 378,499)과 다르다 — 높은 이자율부터 채우기 때문
    assert r["결과"]["필요경비불산입액"] != 2_050_000 * 1_550 // 8_395


def test_direct_jeoksu_gives_same_result():
    assert c(T, {"borrowings": LOANS, "excess_jeoksu": 1_550_000_000})["결과"]["필요경비불산입액"] == 549_726


def test_single_borrowing_is_plain_ratio_and_rate_optional():
    # 1,000,000 × 1,000,000,000 ÷ 5,000,000,000 = 200,000
    r = c(T, {"borrowings": [{"지급이자": 1_000_000, "적수": 5_000_000_000}], "excess_jeoksu": 1_000_000_000})
    assert r["결과"]["필요경비불산입액"] == 200_000


def test_excess_jeoksu_capped_at_borrowing_jeoksu():
    # 시행규칙 제27조제2항 — 초과인출금 적수 3,000,000,000 > 차입금 적수 1,000,000,000 → 지급이자 500,000 전액
    r = c(T, {"borrowings": [{"지급이자": 500_000, "적수": 1_000_000_000}], "excess_jeoksu": 3_000_000_000})
    assert r["결과"]["필요경비불산입액"] == 500_000 and any("제27조제2항" in w for w in r["주의"])


def test_no_excess_and_final_truncation_once():
    assert c(T, {"borrowings": LOANS, "excess_jeoksu": 0})["결과"]["필요경비불산입액"] == 0
    # 원 미만은 합계에서 한 번만 자른다
    r = c(T, {"borrowings": [{"이자율": 5, "지급이자": 200_000, "적수": 300, "제외_적수": 0}, {"이자율": 9, "지급이자": 100_001, "적수": 150}], "excess_jeoksu": 250})
    # 9%: 100,001 전액(적수 150) + 5%: 200,000 × 100 ÷ 300 = 66,666.67 → 166,667.67 → 166,667
    assert r["결과"]["필요경비불산입액"] == 166_667


def test_explicit_excluded_jeoksu_and_construction_interest():
    # 15% 차입금의 채권자불분명분 적수를 직접 500,000,000으로 넣으면 대상 적수 960,000,000 → 450,000 전액, 남은 590,000,000 × 1,600,000 ÷ 7,300,000,000 = 129,315.07
    loans = [LOANS[0], dict(LOANS[1], 제외_적수=500_000_000)]
    assert c(T, {"borrowings": loans, "excess_jeoksu": 1_550_000_000})["결과"]["필요경비불산입액"] == 579_315
    r = c(T, {"borrowings": [{"지급이자": 1_000_000, "적수": 5_000_000_000, "건설자금_이자": 400_000}], "excess_jeoksu": 1_000_000_000})
    # 대상 이자 600,000, 대상 적수 3,000,000,000 → 600,000 × 1 ÷ 3 = 200,000
    assert r["결과"]["필요경비불산입액"] == 200_000 and r["결과"]["선순위_건설자금_이자"] == 400_000


def test_input_errors():
    assert "error" in c(T, {"borrowings": [], "excess_jeoksu": 1})
    assert "error" in c(T, {"borrowings": LOANS})                                             # 적수도 기간도 없음
    assert "error" in c(T, {"borrowings": LOANS, "excess_jeoksu": 1, "months": MONTHS})         # 둘 다
    assert "이자율" in c(T, {"borrowings": [{"지급이자": 1, "적수": 1}, {"지급이자": 1, "적수": 1}], "excess_jeoksu": 1})["error"]
    assert "error" in c(T, {"borrowings": [{"지급이자": 10, "적수": 100, "채권자불분명_이자": 11}], "excess_jeoksu": 1})
    assert "error" in c(T, {"borrowings": LOANS, "months": [{"자산": 1, "부채": 1, "충당금준비금": 2, "일수": 30}]})
