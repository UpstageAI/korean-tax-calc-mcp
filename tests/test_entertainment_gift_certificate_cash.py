"""지역사랑상품권 현금 구입 증명자료(조특령 제130조⑦, 2026.2.27. 신설) — 손계산 사례.

손계산: 시부인 대상 161,000,000 − 한도 78,580,000(일반 76,580,000 + 전통시장등 2,000,000) = 한도초과 82,420,000.
고치기 전에는 상품권 2,000,000을 '영수증 등'으로 넣으면 직부인되고 추가한도가 0이었다(한도초과는 우연히 같고 건물 감액분이 어긋남).
"""
from test_form_templates import c

LEDGER = [{"항목": "카드 3만원 이하", "금액": 2_000_000, "증빙": "적격", "건당기준초과": False},
          {"항목": "법인카드 3만원 초과", "금액": 52_000_000, "증빙": "적격"},
          {"항목": "영수증 3만원 이하", "금액": 1_000_000, "증빙": "영수증 등", "건당기준초과": False},
          {"항목": "건설중인자산 계상", "금액": 3_000_000}, {"항목": "본사건물 계상", "금액": 90_000_000},
          {"항목": "제품 접대 무상제공", "금액": 10_000_000, "성격": "현물", "시가": 10_000_000, "장부가액": 8_000_000}]
REV = {"매출액": 29_900_000_000, "특수관계매출": 2_900_000_000}


def run(item):
    return c("entertainment_adjustment", {"year": 2026, "sme": False, "ledger": LEDGER + [item], "revenue": REV})


def test_cash_purchase_proof_counts_for_limit_and_extra_limit():
    r = run({"항목": "지역사랑상품권(현금 구입)", "금액": 2_000_000, "증빙": "영수증 등", "성격": "지역사랑상품권", "현금구입증명": True})
    assert r["결과"]["시부인_대상"] == 161_000_000 and r["결과"]["한도"] == 78_580_000 and r["결과"]["한도초과"] == 82_420_000
    assert r["결과"]["직부인_기타사외유출"] == 0 and r["계산"]["전통시장한도"] == 2_000_000 and r["계산"]["지역사랑상품권_지출"] == 2_000_000
    assert any("제130조⑦" in w and "제25조②" in w for w in r["주의"])


def test_plain_receipt_still_disallowed_but_warns_by_name():
    r = run({"항목": "영수증 3만원 초과(지역사랑상품권)", "금액": 2_000_000, "증빙": "영수증 등"})
    assert r["결과"]["직부인_기타사외유출"] == 2_000_000 and r["계산"]["전통시장한도"] == 0
    assert any("성격이 '지역사랑상품권'이 아님" in w and "현금구입증명" in w for w in r["주의"])


def test_flag_without_proof_or_before_2026_is_unchanged():
    r = run({"항목": "상품권", "금액": 2_000_000, "증빙": "영수증 등", "성격": "지역사랑상품권"})
    assert r["결과"]["직부인_기타사외유출"] == 2_000_000
