# testcase 1: 급여 + 식사대(2025, 월 20만원 한도, 현물 식사 없음)
#   급여 5,000만원(service_year=2025) → 전액 과세
#   식사대 월 20만원 × 12개월 = 240만원 → min(240만, 20만×12)=240만원 전액 비과세
#   총급여 5,000만, 비과세 합계 240만
#   근로소득공제: 1,200만 + (5,000만−4,500만)×15% = 1,275만
#   근로소득금액 = 5,000만 − 1,275만 = 3,725만
# 근거: 소법§12조3호러목(월 20만원), 소법§47조①(근로소득공제)
# ──────────────────────────────────────────────────────────────────────────────
def test_급여_식사대_2025():
    r = c("earned_income_gross_pay", {"year": 2025, "items": [
        item("급여", 50_000_000, service_year=2025),
        item("식사대", 2_400_000, months=12, meal_provided=False),
    ]})
    assert r["결과"]["총급여액"] == 50_000_000
    assert r["결과"]["비과세_합계"] == 2_400_000
    assert r["결과"]["근로소득공제"] == 12_250_000  # 5천만: 350만+400만+450만+25만 = 1,225만원
    assert r["결과"]["근로소득금액"] == 37_750_000
    # 항목별 확인
    급여항 = next(x for x in r["항목별"] if x["kind"] == "급여")
    assert 급여항["과세액"] == 50_000_000 and 급여항["비과세액"] == 0
    식사항 = next(x for x in r["항목별"] if x["kind"] == "식사대")
    assert 식사항["과세액"] == 0 and 식사항["비과세액"] == 2_400_000
    assert 식사항["비과세_성격"] == "월한도비과세"


