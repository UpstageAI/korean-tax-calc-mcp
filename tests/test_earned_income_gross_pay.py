# 근거: 영§38조①6호, 소법§12조3호저목, 소법§12조3호너목
# ──────────────────────────────────────────────────────────────────────────────
def test_사택제공이익_사회보험료_2025():
    r = c("earned_income_gross_pay", {"year": 2025, "items": [
        item("사택제공이익", 12_000_000, position="종업원"),
        item("사회보험료_사용자부담분", 2_400_000, insurance="건강보험"),
        item("사회보험료_본인부담분_회사대납", 1_500_000),
        item("급여", 50_000_000, service_year=2025),
    ]})
    assert r["결과"]["총급여액"] == 51_500_000  # 급여 5,000만 + 본인부담분 대납 150만
    assert r["결과"]["비과세_합계"] == 14_400_000  # 사택 1,200만 + 사용자부담 240만
    assert r["결과"]["근로소득_아님_합계"] == 0  # 사택(2025 비과세)·사용자부담분 모두 근로소득_아님 아님
    사택항 = next(x for x in r["항목별"] if x["kind"] == "사택제공이익")
    assert 사택항["과세액"] == 0 and 사택항["비과세액"] == 12_000_000
    assert 사택항["비과세_성격"] == "비과세"  # 2025년 비과세 성격
    사용항 = next(x for x in r["항목별"] if x["kind"] == "사회보험료_사용자부담분")
    assert 사용항["과세액"] == 0 and 사용항["비과세액"] == 2_400_000
    대납항 = next(x for x in r["항목별"] if x["kind"] == "사회보험료_본인부담분_회사대납")
