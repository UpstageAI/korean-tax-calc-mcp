"""근로소득 총급여(earned_income_gross_pay) 손계산 정답 테스트.

근거 조문(모두 facts_vocab.json 항목 근거와 일치):
  · 소득세법 제20조①(근로소득 범위), 제12조3호(비과세 각 목), 제47조①(근로소득공제)
  · 시행령 제11조(학자금 3요건), 제12조(자가운전보조금·실비변상여비), 제17조(연장근로수당),
    제17조의2(식사대·출산보육수당), 제17조의3(직무발명보상금), 제17조의4(비과세 복리후생),
    제38조(근로소득에서 제외되는 복리후생), 제49조(수입시기)
"""
import asyncio
import json
from korean_tax_calc_mcp.server import mcp


def c(n, a):
    return json.loads(asyncio.run(mcp.call_tool(n, a)).content[0].text)


# ── helper: facts 없는 항목은 빈 dict로 ──
def F(**kw):
    return {k: v for k, v in kw.items() if v is not None}


def item(kind, amount, **facts):
    d = {"kind": kind, "amount": amount}
    if facts:
        d["facts"] = F(**facts)
    return d


