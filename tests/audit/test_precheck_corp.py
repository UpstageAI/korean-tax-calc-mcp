def res(rid, data):
    r = next(x for x in REGISTRY if x.id == rid and x.세목 == "법인")
    try: return r.fn(Data({**BASE, **data}))["결과"]
    except Missing: return "자료 부족"


def both(rid, good, bad):
    assert res(rid, good) == "이상 없음", (rid, "정상", res(rid, good))
    assert res(rid, {**good, **bad}) == "오류 의심", (rid, "변조")


