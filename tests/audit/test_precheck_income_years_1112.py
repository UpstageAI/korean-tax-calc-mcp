def _sme(y, **m):
    base = {"계약일": f"{y}-03-01", "생년월일": f"{y - 32}-01-01", "청년": True, "감면대상총급여": 40_000_000,
            "취업일": f"{y}-03-01", "최초감면취업일": f"{y}-03-01", "감면최종지급월": f"{y}-12"}
    return W(총급여=40_000_000, 산출세액=3_000_000, 감면세액=m.pop("감면세액", 1_500_000), 중기감면={**base, **m})


def test_wh07_sme_cap_and_rate_by_year():
    assert res("I-WH07", {"귀속연도": 2022, "근로자": [_sme(2022, 감면세액=2_000_000)]}) == "오류 의심"   # 한도 150만
    assert res("I-WH07", {"귀속연도": 2023, "근로자": [_sme(2023, 감면세액=2_000_000)]}) == "이상 없음"   # 한도 200만
    assert res("I-WH07", {"귀속연도": 2022, "근로자": [_sme(2022)]}) == "이상 없음"
    # 2017년 귀속: 청년도 70% — 300만 × 70% = 210만 → 한도 150만
    r = run("I-WH07", {"귀속연도": 2017, "근로자": [_sme(2017, 감면율=0.9)]})
    assert r["결과"] == "오류 의심" and "감면율" in r["내용"]
    low = W(총급여=40_000_000, 산출세액=1_000_000, 감면세액=900_000, 중기감면={"청년": True, "감면대상총급여": 40_000_000})
    assert res("I-WH07", {"귀속연도": 2017, "근로자": [low]}) == "오류 의심"    # 70% → 70만
    assert res("I-WH07", {"귀속연도": 2018, "근로자": [low]}) == "이상 없음"    # 90% → 90만


