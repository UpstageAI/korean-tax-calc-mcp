def test_tool_runs_income_rules_for_tax_소득():
    # 규칙 세목 이름이 '소득·원천'이라 tax='소득'으로 부르면 규칙이 하나도 돌지 않던 문제
    from korean_tax_calc_mcp import server as S
    f = getattr(S.return_precheck, "fn", S.return_precheck)
    w = W(총급여=30_000_000, 근로소득공제=9_750_000, **{"비과세.식대": 2_400_000})
    r22 = f({"귀속연도": 2022, "근로자": [w]}, "소득")
    r23 = f({"귀속연도": 2023, "근로자": [w]}, "소득")
    assert "I-PR05" in [x["규칙"] for x in r22["오류 의심"]]
    assert "I-PR05" in [x["규칙"] for x in r23["이상 없음"]]
    none = f({"근로자": [w]}, "소득")
    assert "I-PR05" in [x["규칙"] for x in none["자료 부족"]]
    g = getattr(S.precheck_schema, "fn", S.precheck_schema)
    rows = {x["키"]: x["필수"] for x in g("소득")["입력스키마"]}
    assert rows["귀속연도"] == "요건별 필수"
