def _rent(g, **m): return W(총급여=g, 월세=m)


def test_pr15_rent_by_year():
    ok = lambda y, w: res("I-PR15", {"귀속연도": y, "근로자": [w]})
    # 2017: 10%만, 한도 750만
    assert ok(2017, _rent(50_000_000, 공제액=750_000, 지급액=9_000_000, 공제율=0.10)) == "이상 없음"
    assert ok(2017, _rent(50_000_000, 공제액=900_000, 지급액=9_000_000, 공제율=0.12)) == "오류 의심"
    # 2018~2022: 5,500만 이하 12%
    assert ok(2019, _rent(50_000_000, 공제액=900_000, 지급액=9_000_000, 공제율=0.12)) == "이상 없음"
    assert ok(2019, _rent(60_000_000, 공제액=900_000, 지급액=9_000_000, 공제율=0.12)) == "오류 의심"
    assert ok(2022, _rent(50_000_000, 공제액=1_275_000, 지급액=9_000_000, 공제율=0.17)) == "오류 의심"
    # 우대 종합소득 기준: 2020년까지 4천만, 2021년부터 4,500만
    assert ok(2020, _rent(50_000_000, 공제액=900_000, 지급액=9_000_000, 공제율=0.12, 종합소득금액=42_000_000)) == "오류 의심"
    assert ok(2021, _rent(50_000_000, 공제액=900_000, 지급액=9_000_000, 공제율=0.12, 종합소득금액=42_000_000)) == "이상 없음"
    # 2023: 17%·15%, 총급여 7천만, 한도 750만 / 2024~: 8천만, 한도 1천만
    assert ok(2023, _rent(50_000_000, 공제액=1_275_000, 지급액=9_000_000, 공제율=0.17)) == "이상 없음"
    assert ok(2023, _rent(75_000_000, 공제액=1_125_000, 지급액=9_000_000, 공제율=0.15)) == "오류 의심"
    assert ok(2024, _rent(75_000_000, 공제액=1_350_000, 지급액=9_000_000, 공제율=0.15)) == "이상 없음"
    assert ok(2023, _rent(50_000_000, 공제액=1_530_000, 지급액=9_000_000, 공제율=0.17)) == "오류 의심"   # 750만 × 17% = 1,275,000
    assert ok(2024, _rent(50_000_000, 공제액=1_530_000, 지급액=9_000_000, 공제율=0.17)) == "이상 없음"


def test_daily_statement_due_dates():
    f = income._daily_due
    assert f(2018, 2) == date(2018, 4, 30) and f(2018, 11) == date(2019, 2, 28)     # 분기 다음 달 말일, 4분기는 2월 말일
    assert f(2019, 5) == date(2019, 7, 10) and f(2019, 9) == date(2019, 10, 10)     # 분기 다음 달 10일
    assert f(2019, 12) == date(2020, 1, 31)                                         # 부칙 제13조① — 시행 후 제출분
    assert f(2020, 1) == date(2020, 4, 30) and f(2021, 6) == date(2021, 7, 31)      # 분기 다음 달 말일
    assert f(2021, 7) == date(2021, 8, 31) and f(2025, 12) == date(2026, 1, 31)     # 매월
    assert f(2024, 1) == date(2024, 2, 29)


