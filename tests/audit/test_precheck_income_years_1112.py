"""사전검토 소득·원천 규칙 연도표(2026-11-12, Claude). 조문은 각 시행본·부칙 대조:
조특법 제30조·조특령 제27조, 조특법 제95조의2, 소득세법 제12조3호·제164조①, 소득세법 시행령 제17조."""
from datetime import date
from korean_tax_calc_mcp.audit.agents.precheck import REGISTRY, Data, Missing
from korean_tax_calc_mcp.audit.agents.precheck import income

R = {r.id: r for r in REGISTRY}


def run(rid, data):
    try: return R[rid].fn(Data(data))
    except Missing as e: return {"결과": "자료 부족", "내용": str(e)}


def res(rid, data): return run(rid, data)["결과"]


def W(**k): return {"성명": "갑", "주민번호": "x", "근무월수": 12, **k}


def test_year_required_and_range():
    w = W(총급여=30_000_000, 근로소득공제=9_750_000)
    assert res("I-WH01", {"근로자": [w]}) == "자료 부족"
    assert res("I-WH01", {"귀속연도": 2015, "근로자": [w]}) == "자료 부족"
    assert res("I-WH01", {"귀속연도": 2027, "근로자": [w]}) == "자료 부족"
    assert res("I-WH01", {"귀속연도": 2020, "근로자": [w]}) == "이상 없음"


