def test_registry_and_run():
    ids = [r.id for r in REGISTRY if r.세목 == "소득·원천"]
    assert all(f"I-PR{n:02d}" in ids for n in range(1, 24))
    assert all(k.split("[")[0].split(".")[0] for k in income.SCHEMA)
    out = run({**base(), "원천세신고.근로소득총지급액": 1}, 세목="소득·원천")
    assert out["요약"]["사실 확인 필요"] == 0 and out["요약"]["오류 의심"] >= 1


