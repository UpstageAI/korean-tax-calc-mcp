def test_p04_p05_deemed_input_by_period():
    # 음식점 개인, 과세표준 1억, 매입 5,000만: 2017-2 8/108·한도 60% → 5,000만 × 8/108 = 3,703,703
    b = {"사업자.업종": "음식점", "사업자.구분": "개인", "의제매입.공제대상가액": 50_000_000, "의제매입.과세표준": 100_000_000}
    assert res("V-P04", {**b, "신고.과세기간": "2017-2", "의제매입.공제세액": 3_703_703}) == "이상 없음"
    # 2018-1부터 과세표준 2억 이하 9/109 → 4,128,440
    assert res("V-P04", {**b, "신고.과세기간": "2018-1", "의제매입.공제세액": 4_128_440}) == "이상 없음"
    assert res("V-P04", {**b, "신고.과세기간": "2017-2", "의제매입.공제세액": 4_128_440}) == "오류 의심"
    # 한도율: 음식점 개인 1억 이하 60%(~2018-1) → 65%(2018-2~) → 75%(2022-1~). 매입 7,000만
    c = {**b, "의제매입.공제대상가액": 70_000_000}
    assert res("V-P05", {**c, "신고.과세기간": "2018-1", "의제매입.공제세액": int(65_000_000 * 9 / 109)}) == "오류 의심"
    assert res("V-P05", {**c, "신고.과세기간": "2018-2", "의제매입.공제세액": int(65_000_000 * 9 / 109)}) == "이상 없음"
    assert res("V-P05", {**c, "신고.과세기간": "2021-2", "의제매입.공제세액": int(70_000_000 * 9 / 109)}) == "오류 의심"
    assert res("V-P05", {**c, "신고.과세기간": "2022-1", "의제매입.공제세액": int(70_000_000 * 9 / 109)}) == "이상 없음"
    # 유흥장소 4/104(~2019) → 2/102(2020~)
    u = {"사업자.업종": "과세유흥장소", "사업자.구분": "개인", "의제매입.공제대상가액": 10_400_000, "의제매입.과세표준": 500_000_000}
    assert res("V-P04", {**u, "신고.과세기간": "2019-2", "의제매입.공제세액": 400_000}) == "이상 없음"
    assert res("V-P04", {**u, "신고.과세기간": "2020-1", "의제매입.공제세액": 400_000}) == "오류 의심"


