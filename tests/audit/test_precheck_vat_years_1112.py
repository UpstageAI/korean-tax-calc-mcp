"""사전검토 부가가치세 규칙 과세기간 연도표(2026-11-12, Claude). 값은 engine.calc_vat 연도표(각 시행본·부칙 대조분)를 경유."""
from korean_tax_calc_mcp.audit.agents.precheck import REGISTRY, Data, Missing, run
from korean_tax_calc_mcp.audit.agents.precheck import vat  # noqa: F401

R = {r.id: r for r in REGISTRY}


def out(rid, data):
    try: return R[rid].fn(Data(data))
    except Missing as e: return {"결과": "자료 부족", "내용": str(e)}


def res(rid, data): return out(rid, data)["결과"]


def test_period_required_and_range():
    base = {"부동산임대.보증금": 100_000_000, "부동산임대.임대일수": 181, "부동산임대.간주임대료": 1_537_260}
    assert res("V-P09", base) == "자료 부족"
    for p in ("2015-2", "2027-1", "2026", "2026-3", "2026-06-30"):
        assert res("V-P09", {**base, "신고.과세기간": p}) == "자료 부족", p
    # run()도 멈추지 않고 자료 부족으로 분류
    r = run({**base, "신고.과세기간": "2027-1"}, "부가")
    assert any(x["규칙"] == "V-P09" for x in r["자료 부족"])


def test_p09_deemed_rent_rate_by_year():
    b = {"부동산임대.보증금": 100_000_000, "부동산임대.임대일수": 181}
    # 2026년 3.1%: 1억 × 3.1% × 181/365 = 1,537,260 / 2021년 1.2%: 595,068 / 2024년(윤년) 3.5%: 1억 × 3.5% × 182/366 = 1,740,437
    assert res("V-P09", {**b, "신고.과세기간": "2026-1", "부동산임대.간주임대료": 1_537_260}) == "이상 없음"
    assert res("V-P09", {**b, "신고.과세기간": "2021-1", "부동산임대.간주임대료": 595_068}) == "이상 없음"
    assert res("V-P09", {**b, "신고.과세기간": "2021-1", "부동산임대.간주임대료": 1_537_260}) == "오류 의심"
    assert res("V-P09", {**b, "부동산임대.임대일수": 182, "신고.과세기간": "2024-1", "부동산임대.간주임대료": 1_740_437}) == "이상 없음"


