from korean_tax_calc_mcp.audit.agents import related as R

P = lambda k: {"구분": k}


def test_paper_2015_figure1():
    """이성태·최기호·윤성만(2015) 회계저널 24(5) <Figure 1>: 2012 사업연도 규정, 상향매출 조정 → 930"""
    people = {"지배주주": P("개인"), "간접출자법인": P("법인"), "수혜법인": P("법인"), "특수관계법인": P("법인")}
    stakes = [("지배주주", "간접출자법인", 0.30), ("간접출자법인", "수혜법인", 0.50), ("지배주주", "수혜법인", 0.25), ("지배주주", "특수관계법인", 0.60)]
    r = R.tunnelling(people, [], stakes, "수혜법인", 100.0, {"간접출자법인": 30.0, "특수관계법인": 30.0}, 10000, "일반", on="2012-12-31")
    g = r["주주별"][0]["증여의제이익"]
    assert g == {"간접출자법인": 180, "직접": 750} and r["합계"] == 930


def test_kinship_by_date():
    fam = [("조부", "부", "부모자녀"), ("부", "나", "부모자녀"), ("조부", "숙부", "부모자녀"), ("숙부", "사촌", "부모자녀"), ("사촌", "오촌", "부모자녀")]
    assert R.kinship(fam, "나", "오촌") == ("혈족", 5)
    assert R.is_kin(fam, "나", "오촌", on="2020-12-31") and not R.is_kin(fam, "나", "오촌", on="2025-12-31")


def test_cycle_geometric():
    st = [("P", "A", 1.0), ("A", "B", 0.03), ("B", "A", 0.10)]
    assert abs(sum(r for _, r in R.paths(st, "P", "B")) - 0.03 / (1 - 0.003)) < 1e-6


