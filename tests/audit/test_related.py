def _ds(people_ind, fam, stakes):
    ppl = {k: P("개인") for k in people_ind} | {"간접": P("법인"), "수혜": P("법인")}
    return R.dominant_shareholder(ppl, fam, stakes, "수혜")[0]


def test_nts2026_dominant_shareholder():
    """책자 제1장 지배주주 판정 예시 2개(13쪽)·사례 4개(15~16쪽)"""
    assert _ds("갑을병정무", [("병", "무", "부모자녀"), ("정", "무", "부모자녀"), ("병", "정", "배우자")],
               [("병", "간접", .4), ("정", "간접", .3), ("무", "간접", .3), ("간접", "수혜", .6), ("갑", "수혜", .25), ("을", "수혜", .15)]) == "병"
    # 예시2: 갑(직접 25%+간접 14%=39%)은 최대주주등이 아니므로 제외 → 병
    assert _ds("갑을병정", [("병", "정", "배우자")],
               [("병", "간접", .5), ("정", "간접", .3), ("갑", "간접", .2), ("간접", "수혜", .7), ("갑", "수혜", .25), ("을", "수혜", .05)]) == "병"
    g = [("갑", "병", "부모자녀"), ("을", "병", "부모자녀"), ("갑", "을", "배우자"), ("A", "B", "부모자녀")]
    base = [("갑", "간접", .6), ("을", "간접", .2), ("병", "간접", .2)]
    assert _ds(["갑", "을", "병", "A", "B"], g, base + [("간접", "수혜", .2), ("A", "수혜", .6), ("B", "수혜", .2)]) == "A"
    assert _ds(["갑", "을", "병", "A", "B"], g, base + [("간접", "수혜", .6), ("A", "수혜", .2), ("B", "수혜", .2)]) == "갑"
    f3 = [("갑", "을", "부모자녀")]
    assert _ds(["갑", "을", "A"], f3, [("갑", "간접", 1.0), ("간접", "수혜", .25), ("A", "수혜", .40), ("을", "수혜", .35)]) == "을"
    assert _ds(["갑", "을", "A"], f3, [("갑", "간접", 1.0), ("간접", "수혜", .35), ("A", "수혜", .40), ("을", "수혜", .25)]) == "갑"


