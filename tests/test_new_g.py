"""개인 주택임대소득(housing_rental_income) 연도별 회귀 — 값은 해당 연도 시행본 조문으로 손계산 (Claude 2026-10-28).

- 소득세법 제12조2호나목: 1주택 비과세(기준시가 9억 초과·국외주택 제외 → 2023 귀속부터 12억, 2022.12.31. 개정 부칙 제11조),
  총수입금액 2천만원 이하 비과세는 2018.12.31. 이전에 끝나는 과세기간까지(2016.12.20. 개정).
- 제14조③7호·제64조의2: 2019.1.1. 이후 발생 소득분부터(법률 제12852호 부칙 제4조) 분리과세 선택 —
  (총수입금액 − 필요경비 50%/등록 60% − 다른 종합소득금액 2천만원 이하면 200만/400만) × 14%.
- 시행령 제122조의2①: 2021~ 단기·아파트 매입 장기일반은 2020.7.10. 이전 등록 신청분만 등록임대주택.
- 제64조의2③2호 의무임대기간: 2020.8.18. 이후 등록 신청분 10년(법률 제17757호 부칙 제13조②), 그 전 4년.
"""
import asyncio, json
from korean_tax_calc_mcp.server import mcp


def c(n, a):
    return json.loads(asyncio.run(mcp.call_tool(n, a)).content[0].text)


def hr(year, houses, **kw):
    return c("housing_rental_income", {"year": year, "houses": houses, **kw})


def test_one_house_exempt_threshold_9eok_to_12eok():
    h = [{"기준시가": 1_000_000_000, "월세": 24_000_000}]
    # 2022: 기준시가 10억 > 9억 → 비과세 제외, 2,400만 > 2천만 → 종합과세 (제12조2호나목 괄호)
    r = hr(2022, h)
    assert r["결과"]["과세"] is True and r["결과"]["구분"] == "종합과세"
    # 2023: 12억 기준(부칙 제11조) → 비과세
    r = hr(2023, h)
    assert r["결과"]["과세"] is False and r["결과"]["구분"] == "비과세(1주택)"
    # 경계: 기준시가 12억 그대로는 '초과'가 아니므로 비과세
    assert hr(2026, [{"기준시가": 1_200_000_000, "월세": 30_000_000}])["결과"]["과세"] is False
    assert hr(2016, [{"기준시가": 900_000_000, "월세": 30_000_000}])["결과"]["과세"] is False


def test_one_overseas_house_taxable_separate():
    # 국외 1주택 월세 1,200만, 다른 종합소득금액 0: (1,200만 − 600만 − 200만) × 14% = 560,000 (제64조의2②)
    r = hr(2023, [{"소재": "국외", "월세": 12_000_000}], other_income_amount=0)
    assert r["결과"]["구분"] == "분리과세 선택 가능"
    assert r["결과"]["분리과세_사업소득금액"] == 4_000_000 and r["결과"]["분리과세_세액"] == 560_000
    assert r["결과"]["분리과세_지방소득세"] == 56_000


def test_small_revenue_exempt_until_2018_then_separate():
    hs = [{"기준시가": 500_000_000, "월세": 15_000_000},
          {"소유자": "배우자", "기준시가": 300_000_000}]          # 부부 합산 2주택(시행령 제8조의2③4호)
    r = hr(2018, hs)
    assert r["결과"]["과세"] is False and r["결과"]["구분"].startswith("비과세(총수입금액")
    assert r["결과"]["주택_수"] == 2
    # 2019: 분리과세 선택, 다른 종합소득금액 3천만 > 2천만 → 추가 차감 없음: 1,500만 × 50% × 14% = 1,050,000
    r = hr(2019, hs, other_income_amount=30_000_000)
    assert r["결과"]["분리과세_세액"] == 1_050_000
    # 종합과세 참고: 2019 기본세율 1,200만~4,600만 15% → (3,000만 + 750만) − 3,000만 = 750만 × 15% = 1,125,000
    r = hr(2019, hs, other_income_amount=30_000_000, other_taxable_base=30_000_000, comprehensive_rental_income=7_500_000)
    assert r["결과"]["종합과세_주택임대분_세액_참고"] == 1_125_000
    assert any("분리과세가 적음" in d["결론"] for d in r["판단"])


def test_over_20m_comprehensive_any_year():
    hs = [{"기준시가": 300_000_000, "월세": 10_000_000}, {"기준시가": 300_000_000, "월세": 15_000_000}]
    for y in (2016, 2019, 2026):
        r = hr(y, hs)
        assert r["결과"]["구분"] == "종합과세" and r["결과"]["총수입금액"] == 25_000_000, y


def test_registered_and_general_mix_2021():
    # 등록(장기일반, 비아파트, 2019 신청) 월세 1,200만 + 일반 800만 = 2,000만(≤ 2천만), 다른 종합소득금액 1,000만
    # 경비 1,200만×60% + 800만×50% = 1,120만, 추가 차감 400만×12/20 + 200만×8/20 = 320만 (시행령 제122조의2 안분식)
    # (2,000만 − 1,120만 − 320만) = 560만 × 14% = 784,000
    hs = [{"이름": "A", "기준시가": 400_000_000, "월세": 12_000_000, "등록임대": True, "임대유형": "장기일반", "등록신청일": "2019-05-01"},
          {"이름": "B", "기준시가": 300_000_000, "월세": 8_000_000}]
    r = hr(2021, hs, other_income_amount=10_000_000)
    assert r["결과"]["분리과세_사업소득금액"] == 5_600_000 and r["결과"]["분리과세_세액"] == 784_000
    assert r["결과"]["의무임대기간"][0]["의무임대기간_년"] == 4
    # 2020.8.18. 이후 신청분은 10년(법률 제17757호 부칙 제13조②)
    hs[0]["등록신청일"] = "2020-09-01"
    assert hr(2021, hs, other_income_amount=10_000_000)["결과"]["의무임대기간"][0]["의무임대기간_년"] == 10


def test_short_term_registration_cutoff():
    hs = [{"이름": "A", "기준시가": 300_000_000, "월세": 10_000_000, "등록임대": True, "임대유형": "단기", "아파트": True, "등록신청일": "2020-08-01"},
          {"이름": "B", "기준시가": 300_000_000, "월세": 0}]
    # 2019 시행본: 단기도 등록임대 → (1,000만 − 600만 − 400만) = 0
    assert hr(2019, hs, other_income_amount=0)["결과"]["분리과세_세액"] == 0
    # 2021~: 2020.7.10. 후 신청 단기는 제외 → 일반 50%: (1,000만 − 500만 − 200만) × 14% = 420,000
    assert hr(2021, hs, other_income_amount=0)["결과"]["분리과세_세액"] == 420_000
    # 2020 귀속은 개정 시행령 적용 시점 미확인 → 멈춤
    assert "입력 확인 필요" in hr(2020, hs, other_income_amount=0)["error"]
    # 7.10. 이전 신청이면 2021에도 등록임대
    hs[0]["등록신청일"] = "2020-07-10"
    assert hr(2021, hs, other_income_amount=0)["결과"]["분리과세_세액"] == 0


def test_deemed_rent_included_in_revenue():
    # 2019, 본인 3주택(50㎡·3억 — 2019 소형 기준 40㎡·2억 초과라 주택 수 포함), 보증금 A 3억·B 2억, C 월세 600만
    # 간주임대료: (5억 − 3억, 적수 큰 A부터 차감) → B 2억 × 365 × 60% ÷ 365 × 2.1% = 2,520,000 (제25조①, 시행령 제53조③)
    hs = [{"이름": "A", "기준시가": 300_000_000, "면적": 50, "보증금": 300_000_000},
          {"이름": "B", "기준시가": 300_000_000, "면적": 50, "보증금": 200_000_000},
          {"이름": "C", "기준시가": 300_000_000, "면적": 50, "월세": 6_000_000}]
    r = hr(2019, hs, other_income_amount=0, rate=0.021)
    간주 = r["결과"]["간주임대료"]
    assert abs(간주 - 2_520_000) <= 1
    assert r["결과"]["총수입금액"] == 6_000_000 + 간주
    소득 = (6_000_000 + 간주) - (6_000_000 + 간주) // 2 - 2_000_000
    assert abs(r["결과"]["분리과세_사업소득금액"] - 소득) <= 1


def test_spouse_houses_count_but_deposit_not_own():
    # 본인 1채(보증금 5억) + 배우자 2채(보증금 있음) → 3주택이지만 본인 보증금 5억만 합산 — 간주임대료 대상
    hs = [{"기준시가": 500_000_000, "면적": 84, "보증금": 500_000_000},
          {"소유자": "배우자", "기준시가": 500_000_000, "면적": 84, "보증금": 400_000_000},
          {"소유자": "배우자", "기준시가": 500_000_000, "면적": 84}]
    r = hr(2023, hs, other_income_amount=0, rate=0.029)
    # (5억 − 3억) × 60% × 2.9% = 3,480,000
    assert abs(r["결과"]["간주임대료"] - 3_480_000) <= 1


def test_unsupported_inputs_stop():
    assert "겸용" in hr(2023, [{"기준시가": 300_000_000, "월세": 1, "겸용": True}])["문제"][0]
    assert "공동소유" in hr(2023, [{"기준시가": 300_000_000, "월세": 1, "공동소유": True}])["문제"][0]
    # 2019~ 2천만 이하인데 다른 종합소득금액 없으면 멈춤
    r = hr(2019, [{"기준시가": 300_000_000, "월세": 5_000_000}, {"기준시가": 300_000_000}])
    assert "other_income_amount" in r["문제"][0]
    # 등록임대인데 임대유형 없음
    r = hr(2022, [{"기준시가": 300_000_000, "월세": 5_000_000, "등록임대": True}, {"기준시가": 300_000_000}], other_income_amount=0)
    assert "임대유형" in r["문제"][0]


